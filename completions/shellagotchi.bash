    local i cur prev opts cmd
    COMPREPLY=()
    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
        cur="$2"
    else
        cur="${COMP_WORDS[COMP_CWORD]}"
    fi
    prev="$3"
    cmd=""
    opts=""

    for i in "${COMP_WORDS[@]:0:COMP_CWORD}"
    do
        case "${cmd},${i}" in
            ",$1")
                cmd="shellagotchi"
                ;;
            shellagotchi,daemon)
                cmd="shellagotchi__subcmd__daemon"
                ;;
            shellagotchi,doctor)
                cmd="shellagotchi__subcmd__doctor"
                ;;
            shellagotchi,feed)
                cmd="shellagotchi__subcmd__feed"
                ;;
            shellagotchi,gen-completions)
                cmd="shellagotchi__subcmd__gen__subcmd__completions"
